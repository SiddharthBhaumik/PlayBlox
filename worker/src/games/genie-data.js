function slugify(name) {
  return name.normalize("NFKD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

const questionIds = new Set(GENIE_QUESTIONS.map(question => question.id));

export const GENIE_CHARACTERS = RAW_CHARACTERS.map(([name, emoji, description, traitList]) => {
  const traits = {};
  for (const token of traitList.trim().split(/\s+/)) {
    const partial = token.startsWith("~");
    const id = partial ? token.slice(1) : token;
    if (!questionIds.has(id)) throw new Error(`Unknown genie trait "${id}" on ${name}`);
    traits[id] = partial ? 0.5 : 1;
  }
  return Object.freeze({ id: slugify(name), name, emoji, description, traits: Object.freeze(traits) });
});
